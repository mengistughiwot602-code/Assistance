import streamlit as st
import os
from crewai import Agent, Crew, Process, Task
from crewai_tools import SerperDevTool

st.set_page_config(page_title="Autonomous Research Assistant", layout="wide")
st.title("🔍 Autonomous Multi-Agent Research Assistant")
st.write("Input a research topic below to command an autonomous crew to investigate and draft a report for you!")

# User Input API Keys inside the Web App Sidebar
with st.sidebar:
    st.header("Please fill those fields first")
    openai_key = st.text_input("OpenAI API Key", type="password")
    serper_key = st.text_input("Serper API Key", type="password")
    st.markdown("--- ")
    st.markdown("Generated by DSstudents@bdu")

topic = st.text_input("Enter your research topic:", value="")

if st.button("Start Autonomous Research"):
    if not openai_key or not serper_key:
        st.error("Please provide both API keys in the sidebar.")
    elif not topic.strip():
        st.warning("Please enter a valid research topic.")
    else:
        # Set Environment variables
        os.environ["OPENAI_API_KEY"] = openai_key
        os.environ["SERPER_API_KEY"] = serper_key
        os.environ["OPENAI_MODEL_NAME"] = "gpt-4o-mini"

        with st.status("Agents are working...", expanded=True) as status:
            st.write("Initializing Web Search tools...")
            search_tool = SerperDevTool()

            st.write("Briefing agents...")
            researcher = Agent(
                role="Lead Web Researcher",
                goal=f"Search the web and extract the latest advancements regarding {topic}",
                backstory="You are a meticulous researcher. You use search tools to find facts.",
                tools=[search_tool],
                verbose=True
            )

            writer = Agent(
                role="Lead Technical Writer",
                goal=f"Synthesize technical findings into an executive-grade Markdown report about {topic}",
                backstory="You write clear and logical markdown reports.",
                verbose=True
            )

            st.write("Formulating tasks...")
            search_task = Task(
                description=f"Gather details about {topic}. Be thorough.",
                expected_output="A detailed comprehensive outline of recent facts and URLs.",
                agent=researcher
            )

            write_task = Task(
                description=f"Draft a polished markdown report on {topic} based on the research.",
                expected_output="A comprehensive report in Markdown.",
                agent=writer
            )

            st.write("Starting execution cycle...")
            crew = Crew(
                agents=[researcher, writer],
                tasks=[search_task, write_task],
                process=Process.sequential
            )

            result = crew.kickoff()
            status.update(label="Research Completed successfully!", state="complete")

        st.subheader("Final Generated Report")
        st.markdown(result)
